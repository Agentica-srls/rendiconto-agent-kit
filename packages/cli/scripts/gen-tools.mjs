// Generates src/generated/tools.ts from a tools.json.
//   npm run gen                       -> tools.pinned.json (default)
//   RENDICONTO_TOOLS_URL=<url> npm run gen   -> fetch the live registry
//   node scripts/gen-tools.mjs --url https://rendiconto.io/api/agent/v1/tools.json
//   node scripts/gen-tools.mjs --if-missing  -> skip when the output already exists
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "src/generated/tools.ts");
const args = process.argv.slice(2);
const urlIdx = args.indexOf("--url");
const url = urlIdx >= 0 ? args[urlIdx + 1] : process.env.RENDICONTO_TOOLS_URL;

if (args.includes("--if-missing")) {
  try {
    await access(out);
    process.exit(0);
  } catch {
    /* generate */
  }
}

let doc;
if (url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  doc = await res.json();
} else {
  doc = JSON.parse(await readFile(resolve(root, "tools.pinned.json"), "utf8"));
}
if (!doc || !Array.isArray(doc.tools)) throw new Error("tools.json: expected { version, tools: [] }");

const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const chunks = [];
const map = [];
const meta = {};
for (const t of doc.tools) {
  const name = `${pascal(t.name)}Input`;
  const schema = { ...t.inputSchema };
  delete schema.$schema;
  chunks.push(
    await compile(schema, name, {
      bannerComment: "",
      additionalProperties: false,
      format: false,
      unreachableDefinitions: false,
      strictIndexSignatures: false,
    })
  );
  map.push(`  ${t.name}: ${name};`);
  meta[t.name] = {
    risk: t.risk,
    confirmWhen: t.confirmWhen ?? null,
    write: !!t.write,
    scope: t.scope,
    ai: !!t.ai,
    idempotent: !!(t.inputSchema.properties && t.inputSchema.properties.idempotencyKey),
  };
}

const body = [
  "/* eslint-disable */",
  "// GENERATED by scripts/gen-tools.mjs from tools.json. Do not edit.",
  `// registry version: ${doc.version}, tools: ${doc.tools.length}`,
  "",
  ...chunks,
  "export interface ToolInputs {",
  ...map,
  "}",
  "",
  "export type ToolName = keyof ToolInputs;",
  `export const REGISTRY_VERSION = ${JSON.stringify(doc.version)};`,
  `export const TOOL_NAMES = ${JSON.stringify(doc.tools.map((t) => t.name), null, 2)} as const;`,
  "",
  "export interface ToolMeta {",
  '  risk: "normal" | "confirm";',
  '  confirmWhen: "always" | "bulk" | "conditional" | null;',
  "  write: boolean;",
  "  scope: string[];",
  "  ai: boolean;",
  "  idempotent: boolean;",
  "}",
  `export const TOOL_META: Record<ToolName, ToolMeta> = ${JSON.stringify(meta, null, 2)} as Record<ToolName, ToolMeta>;`,
  "",
].join("\n");

await mkdir(dirname(out), { recursive: true });
await writeFile(out, body);
console.log(`wrote ${out} (${doc.tools.length} tools, registry ${doc.version})`);
